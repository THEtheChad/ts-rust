def sgn(x) -> str:
    return f"{x:+d}" if isinstance(x, int) else f"{x:+.2f}"


def md_snapshot(s: dict, top: int = 20) -> list[str]:
    t = s["totals"]
    fp = s["functions"]["prod"]
    o = [f"### Snapshot {s['sha'][:9]} (crates tree {s['tree'][:9]})", ""]
