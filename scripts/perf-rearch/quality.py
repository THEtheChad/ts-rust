# file classification
#
# `test_spans` (with `item_end`, `is_test_attr`, `resolve_mod`) splits the *source* into prod and
# test lines for the source metrics only: line counts, functions and complexity, duplication,
# hygiene and churn. It never decides what ships: the escape-hatch inventory and `gating` read
# rustc's expanded source (qexpand.py), and no feature cfg is read anywhere here.


def classify_path(path: str) -> str | None:
    """'test' for test-only files by path, None for undecided."""
    parts = path.split("/")
    base = parts[-1]
    if any(p in ("tests", "benches", "examples") for p in parts[:-1]):
        return "test"
    if base.endswith(("_test.rs", "_tests.rs")) or base in ("tests.rs", "test.rs"):
        return "test"
    return None


def is_generated(path: str, head: str) -> bool:
    if "/lsp_generated/" in path or path.endswith("_generated.rs"):
        return True
    return bool(GEN_HEAD_RE.search(head))


def match_close(texts: list[str], i: int, open_: str, close: str) -> int:
    depth = 0
    for j in range(i, len(texts)):
        t = texts[j]
        if t == open_:
            depth += 1
        elif t == close:
            depth -= 1
            if depth == 0:
                return j
    return len(texts) - 1


def skip_attr(texts: list[str], i: int) -> int:
    """i at '#'; returns index after the attribute."""
    j = i + 1
    if j < len(texts) and texts[j] == "!":
        j += 1
    if j < len(texts) and texts[j] == "[":
        return match_close(texts, j, "[", "]") + 1
    return i + 1


def attr_body(texts: list[str], i: int) -> tuple[list[str], int]:
    j = i + 1
    if j < len(texts) and texts[j] == "!":
        j += 1
    end = match_close(texts, j, "[", "]")
    return texts[j + 1 : end], end + 1


# Items whose body (a `{ ... }` at depth 0, or a `;`) ends them: `fn`, `impl`, `mod`, ... and the
# statements that are blocks (`if`, `match`, loops, `unsafe { }`, a bare block).
BLOCK_ITEM_KW = {"fn", "impl", "mod", "trait", "struct", "enum", "union", "if", "match", "for", "while",
                 "loop", "unsafe", "async", "extern", "macro_rules", "{"}


def item_end(texts: list[str], j: int) -> int:
    """The index of the last token of the item, statement, struct field (of a struct or a struct
    literal), enum variant or match arm that starts at token `j` (after its attributes).

    - An item or block statement (`BLOCK_ITEM_KW`, `const fn`) ends with its first `{ ... }` at
      depth 0 (an `if`'s `else` branches too), or at a `;` at depth 0 (`mod x;`, `struct S;`).
    - Anything else (a field, a `let` or expression statement, a `const`/`static`/`use`, a variant,
      a match arm) ends at the first `,` or `;` at depth 0, with `(...)`, `[...]` and `{...}`
      nested; a `{` after `=>` (an arm's block) or after `!` (a macro call such as
      `thread_local! { }`) ends it with its `}`; a closer of the enclosing struct, call or block
      ends it before that closer (a last field with no comma).
    Strings and chars are single tokens (`lex`), so their brackets and commas do not count."""
    n = len(texts)
    k = j
    if k < n and texts[k] == "pub":
        k += 1
        if k < n and texts[k] == "(":
            k = match_close(texts, k, "(", ")") + 1
    first = texts[k] if k < n else ""
    block = first in BLOCK_ITEM_KW or (first == "const" and k + 1 < n and texts[k + 1] in ("fn", "unsafe", "async"))
    depth = 0
    prev = None
    while k < n:
        t = texts[k]
        if block:
            if t in ("(", "["):
                depth += 1
            elif t in (")", "]"):
                depth -= 1
            elif depth == 0 and t == ";":
                return k
            elif depth == 0 and t == "{":
                end = match_close(texts, k, "{", "}")
                if end + 1 < n and texts[end + 1] == "else":
                    k = end + 1
                    continue
                return end
            elif depth == 0 and t == "}":
                return max(j, k - 1)
        else:
            if t in ("(", "[", "{"):
                if t == "{" and depth == 0 and prev in ("=>", "!"):
                    return match_close(texts, k, "{", "}")
                depth += 1
            elif t in (")", "]", "}"):
                if depth == 0:
                    return max(j, k - 1)
                depth -= 1
            elif depth == 0 and t in (",", ";"):
                return k
            if depth == 0:
                prev = t
        k += 1
    return n - 1


def is_test_attr(body: list[str]) -> bool:
    if body == ["test"] or (len(body) >= 3 and body[-1] == "test" and body[-2] == "::"):
        return True  # #[test], #[tokio::test]
    if body[:1] == ["cfg"]:
        s = "".join(body)
        return s == "cfg(test)" or s.startswith("cfg(all(test,") or s.startswith("cfg(all(test)")
    return False


def test_spans(texts: list[str], lines: list[int]):
    """Line spans of #[cfg(test)] / #[test] items, and names of `#[cfg(test)] mod x;` files."""
    spans: list[tuple[int, int]] = []
    mods: list[tuple[str, str | None]] = []
    n = len(texts)
    i = 0
    while i < n:
        if texts[i] == "#" and i + 1 < n and texts[i + 1] == "[":
            body, after = attr_body(texts, i)
            if is_test_attr(body):
                start_line = lines[i]
                j = after
                path_attr = None
                while j < n and texts[j] == "#":  # more attributes
                    b2, j2 = attr_body(texts, j)
                    if b2[:1] == ["path"] and len(b2) >= 3:
                        path_attr = b2[2].strip('"')
                    j = j2
                if j >= n:
                    break
                end = item_end(texts, j)
                if texts[end] == ";" and end >= 2 and texts[end - 2] == "mod":
                    mods.append((texts[end - 1], path_attr))
                spans.append((start_line, lines[end]))
                i = end + 1
                continue
            i = after
            continue
        i += 1
    # merge
    spans.sort()
    merged: list[list[int]] = []
    for a, b in spans:
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return merged, mods


def resolve_mod(parent: str, name: str, path_attr: str | None, files: set[str]) -> list[str]:
    d = os.path.dirname(parent)
    if path_attr:
        p = os.path.normpath(os.path.join(d, path_attr))
        return [p] if p in files else []
    base = os.path.basename(parent)
    stem = base[:-3]
    roots = [d] if base in ("mod.rs", "lib.rs", "main.rs") or base.endswith("_root.rs") else [os.path.join(d, stem), d]
    for r in roots:
        for c in (f"{r}/{name}.rs", f"{r}/{name}/mod.rs"):
            if c in files:
                return [c]
    return []


def in_spans(spans, line: int) -> bool:
    # spans: sorted list of [a, b]
    lo, hi = 0, len(spans)
    while lo < hi:
        mid = (lo + hi) // 2
        if spans[mid][1] < line:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(spans) and spans[lo][0] <= line


def area_of(path: str) -> str:
    p = path.split("/")
    if len(p) >= 3 and p[1] == "ts_goport" and p[2] == "src":
        top = p[3] if len(p) > 3 else ""
        return "ts_goport/" + (top[:-3] if top.endswith(".rs") else top)
    if len(p) >= 4 and p[1] == "ts_goport" and p[2] == "parts":
        return "ts_goport/parts/" + p[3]
    if len(p) >= 3 and p[1] == "ts_goport":
        return "ts_goport/" + p[2]
    return p[1] if len(p) > 1 else path


