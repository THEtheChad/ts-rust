class SourceFiles:
    """The lexed source files of a revision, read on first use (`git show`): what `gating` needs
    of the source (lines for the report) without measuring the whole tree."""

    def __init__(self, sha: str):
        self.sha = sha
        self.done: dict[str, dict | None] = {}

    def get(self, path: str):
        if path not in self.done:
            try:
                src = git("show", f"{self.sha}:{path}")
            except subprocess.CalledProcessError:
                self.done[path] = None
            else:
                kinds, texts, lines, _ = lex(src)
                self.done[path] = {"kinds": kinds, "texts": texts, "lines": lines, "funcs": fn_spans(kinds, texts, lines)}
        return self.done[path]

    def __contains__(self, path: str) -> bool:
        return self.get(path) is not None

    def __getitem__(self, path: str) -> dict:
        a = self.get(path)
        if a is None:
            raise KeyError(path)
        return a


