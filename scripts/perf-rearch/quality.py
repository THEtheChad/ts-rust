def sgn(x) -> str:
    return f"{x:+d}" if isinstance(x, int) else f"{x:+.2f}"


def md_snapshot(s: dict, top: int = 20) -> list[str]:
    t = s["totals"]
    fp = s["functions"]["prod"]
    o = [f"### Snapshot {s['sha'][:9]} (crates tree {s['tree'][:9]})", ""]
    o.append(f"- Code lines: prod {t.get('code_prod', 0):,}, test {t.get('code_test', 0):,} "
             f"(files: prod {t.get('files_prod', 0)}, test {t.get('files_test', 0)}; generated excluded: {t.get('files_generated', 0)} files, {t.get('lines_generated', 0):,} lines)")
    o.append(f"- Prod functions {fp['count']:,}: cognitive p50 {fp['cog']['p50']}, p90 {fp['cog']['p90']}, p99 {fp['cog']['p99']}, max {fp['cog']['max']}; "
             f">25: {fp['cog']['gt25']}, >50: {fp['cog']['gt50']}. Cyclomatic p50 {fp['cyc']['p50']}, p90 {fp['cyc']['p90']}, max {fp['cyc']['max']}; >25: {fp['cyc']['gt25']}, >50: {fp['cyc']['gt50']}")
    hs = s["hatches"]
    read = [h for h in hs if h["read_in_prod"]]
    feat_only = [h for h in hs if not h["read_in_prod"] and h["features"]]
    cls = Counter(h["class"] for h in hs)
    o.append(f"- Escape-hatch classes: behavior switches {cls['behavior']}, tuning knobs {cls['tuning']}, diagnostics {cls['diagnostic']}, "
             f"verification {cls['verification']}, test hooks {cls['test-hook']}")
    o.append(f"- Escape hatches: {len(read)} distinct GOPORT_*/TSC_RS_* env names read in shipped prod code ({sum(1 for h in hs if h['fallback'])} are switches: "
             f"a bool gate or a branch at the read); {len(feat_only)} more only under non-default cargo features "
             f"({', '.join(sorted({f for h in feat_only for f in h['features']})) or '-'}); {len(hs) - len(read) - len(feat_only)} only set or defined; "
             f"bool gates {len(s['gates'])} with {sum(g['branch'] for g in s['gates'].values())} branch uses; cfg features in prod code {len(s['features'])}")
    du = s["dup"]
    o.append(f"- Duplication (prod, ≥{du['min_tokens']} tokens and ≥{du['min_lines']} lines): {du['pct']}% of prod code lines "
             f"({du['dup_lines']:,} / {du['prod_code_lines']:,}), {len(du['blocks'])} blocks")
    h = s["hygiene"]["prod"]
    o.append("- Hygiene (prod): " + ", ".join(f"{k} {h.get(k, 0)}" for k in ("unsafe", "unsafe_block", "unwrap", "expect", "panic!", "unreachable!", "todo!", "allow_attr", "expect_attr", "TODO", "FIXME", "HACK", "XXX")))
    if "clippy" in s:
        for name in ("config", "forced"):
            c = s["clippy"][name]
            label = "repo config" if name == "config" else "--force-warn clippy::all"
            o.append(f"- Clippy ({label}): {c['total']} warnings ({'ok' if c['ok'] else 'FAILED rc=' + str(c['rc'])}, {c['seconds']} s); top: "
                     + (", ".join(f"{k.removeprefix('clippy::')} {v}" for k, v in list(c["by_lint"].items())[:8]) or "-"))
    o.append("")
    o.append(f"Top {top} prod functions by cognitive complexity:")
    o.append("")
    o.append("| cog | cyc | sloc | function |")
    o.append("|---:|---:|---:|---|")
    for f in sorted(s["funcs"], key=lambda f: -f["cog"])[:top]:
        o.append(f"| {f['cog']} | {f['cyc']} | {f['sloc']} | `{f['file'].removeprefix('crates/ts_goport/src/')}:{f['start']}` {f['name']} |")
    o.append("")
    return o


def md_hatches(s: dict) -> list[str]:
    o = ["Escape-hatch inventory (prod; `switch` = read into a bool gate or branched on at the read):", "",
         "| env | class | switch | reads | direct branches | bool gates (branch uses/all uses) | sets | only under feature | files |", "|---|---|---|---:|---:|---|---:|---|---|"]
    for h in s["hatches"]:
        g = ", ".join(f"{s['gates'][x]['name']} ({s['gates'][x]['branch']}/{s['gates'][x]['branch'] + s['gates'][x]['other']})" for x in h["gates"]) or "-"
        o.append(f"| {h['name']} | {h['class']} | {'yes' if h['fallback'] else ''} | {h['reads']} | {h['direct_branches']} | {g} | {h['sets']} | "
                 f"{', '.join(h['features']) if not h['read_in_prod'] else ''} | "
                 + ", ".join(f.removeprefix("crates/ts_goport/src/") for f in h["files"][:3]) + (" …" if len(h["files"]) > 3 else "") + " |")
    o.append("")
    return o


def md_delta(d: dict, label: str = "") -> list[str]:
    c = d["churn"]
    o = [f"### Delta {d['base']} → {d['rev']} {label}".rstrip(), ""]
    o.append(f"- Churn: prod +{c['prod_add']}/−{c['prod_del']} (net {sgn(c['prod_net'])}), test +{c['test_add']}/−{c['test_del']} (net {sgn(c['test_net'])}), "
             f"generated +{c['generated_add']}/−{c['generated_del']}; files touched {c['files_touched']} (prod {c['files_prod']}, test {c['files_test']}); test:prod added {c['test_to_prod_add']}")
    hc = d["hatch_counts"]
    o.append(f"- Escape hatches read in shipped prod code: {hc['base']} → {hc['rev']} (switches {hc['fallback_base']} → {hc['fallback_rev']}); "
             f"gate branch uses {d['gates_branch']['base']} → {d['gates_branch']['rev']}; by class: "
             + ", ".join(f"{c} {v[0]}→{v[1]}" for c, v in d["hatch_classes"].items()))
    for h in d["hatches_new"]:
        kind = h["class"] + (", switch" if h["fallback"] else "") + (", only under " + ",".join(h["features"]) if not h["read_in_prod"] and h["features"] else "")
        o.append(f"  - NEW `{h['name']}` ({kind}): reads {h['reads']}, direct branches {h['direct_branches']}, gates {', '.join(x.split('@')[0] for x in h['gates']) or '-'} "
                 f"(branch uses {h['gate_branch_uses']}), sets {h['sets']} — " + "; ".join(x.removeprefix('crates/ts_goport/src/') for x in h["sites"][:4]))
    for n in d["hatches_removed"]:
        o.append(f"  - removed `{n}`")
    for h in d["hatches_changed"]:
        o.append(f"  - changed `{h['name']}`: reads {h['reads'][0]}→{h['reads'][1]}, direct branches {h['direct_branches'][0]}→{h['direct_branches'][1]}, "
                 f"gate branch uses {h['gate_branch_uses'][0]}→{h['gate_branch_uses'][1]}, sets {h['sets'][0]}→{h['sets'][1]}"
                 + (("; new: " + "; ".join(x.removeprefix('crates/ts_goport/src/') for x in h["new_sites"][:4])) if h["new_sites"] else ""))
    if d["features_new"]:
        o.append(f"  - new cfg features: {', '.join(d['features_new'])}")
    f = d["functions"]
    o.append(f"- Prod functions {f['count'][0]} → {f['count'][1]} (new {d['functions_new']}, removed {d['functions_removed']}); "
             f"cognitive p90 {f['p90'][0]}→{f['p90'][1]}, max {f['max'][0]}→{f['max'][1]}, >25 {f['gt25'][0]}→{f['gt25'][1]}, >50 {f['gt50'][0]}→{f['gt50'][1]}, "
             f"sum {f['sum'][0]}→{f['sum'][1]}; cyclomatic >25 {f['cyc_gt25'][0]}→{f['cyc_gt25'][1]}")
    if d["functions_grown"]:
        o.append(f"  - functions new with cog >25 or grown by ≥5 ({d['functions_grown_count']}):")
        for g in d["functions_grown"][:10]:
            o.append(f"    - `{g['key'].removeprefix('crates/ts_goport/src/')}` cog {g['cog'][0]}→{g['cog'][1]}, cyc {g['cyc'][0]}→{g['cyc'][1]}, sloc {g['sloc'][0]}→{g['sloc'][1]}")
    du = d["dup"]
    o.append(f"- Duplication: {du['pct'][0]}% → {du['pct'][1]}% ({du['lines'][0]} → {du['lines'][1]} lines, blocks {du['blocks'][0]} → {du['blocks'][1]}, new blocks {du['new_block_count']})")
    for b in du["new_blocks"][:5]:
        o.append(f"  - {b['lines']} lines / {b['tokens']} tokens: `{b['a'].removeprefix('crates/ts_goport/src/')}` = `{b['b'].removeprefix('crates/ts_goport/src/')}`")
    hy = d["hygiene"]
    ch = [f"{k} {v[0]}→{v[1]}" for k, v in hy.items() if v[0] != v[1]]
    o.append("- Hygiene (prod) changes: " + (", ".join(ch) if ch else "none"))
    for k, v in list(d["hygiene_file_changes"].items())[:6]:
        o.append(f"  - {k.removeprefix('crates/ts_goport/src/')}: {sgn(v)}")
    if "clippy" in d:
        for name, label in (("config", "repo config"), ("forced", "--force-warn clippy::all")):
            cl = d["clippy"][name]
            o.append(f"- Clippy ({label}): {cl['total'][0]} → {cl['total'][1]}"
                     + ("; " + ", ".join(f"{k.removeprefix('clippy::')} {sgn(v)}" for k, v in list(cl["by_lint_delta"].items())[:8]) if cl["by_lint_delta"] else ""))
    o.append("")
    return o


