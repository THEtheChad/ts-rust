def classify_path(path: str) -> str | None:
    """'test' for test-only files by path, None for undecided."""
    parts = path.split("/")
    base = parts[-1]
    if any(p in ("tests", "benches", "examples") for p in parts[:-1]):
        return "test"
    if base.endswith(("_test.rs", "_tests.rs")) or base in ("tests.rs", "test.rs"):
        return "test"
    return None


def is_generated(path: str, head: str) -> bool:
    if "/lsp_generated/" in path or path.endswith("_generated.rs"):
        return True
    return bool(GEN_HEAD_RE.search(head))


def match_close(texts: list[str], i: int, open_: str, close: str) -> int:
    depth = 0
    for j in range(i, len(texts)):
        t = texts[j]
        if t == open_:
            depth += 1
        elif t == close:
            depth -= 1
            if depth == 0:
                return j
    return len(texts) - 1


def skip_attr(texts: list[str], i: int) -> int:
    """i at '#'; returns index after the attribute."""
    j = i + 1
    if j < len(texts) and texts[j] == "!":
        j += 1
    if j < len(texts) and texts[j] == "[":
        return match_close(texts, j, "[", "]") + 1
    return i + 1


def attr_body(texts: list[str], i: int) -> tuple[list[str], int]:
    j = i + 1
    if j < len(texts) and texts[j] == "!":
        j += 1
    end = match_close(texts, j, "[", "]")
    return texts[j + 1 : end], end + 1


def is_test_attr(body: list[str]) -> bool:
    if body == ["test"] or (len(body) >= 3 and body[-1] == "test" and body[-2] == "::"):
        return True  # #[test], #[tokio::test]
    if body[:1] == ["cfg"]:
        s = "".join(body)
        return s == "cfg(test)" or s.startswith("cfg(all(test,") or s.startswith("cfg(all(test)")
    return False


def test_spans(texts: list[str], lines: list[int]):
    """Line spans of #[cfg(test)] / #[test] items, and names of `#[cfg(test)] mod x;` files."""
    spans: list[tuple[int, int]] = []
    mods: list[tuple[str, str | None]] = []
    n = len(texts)
    i = 0
    while i < n:
        if texts[i] == "#" and i + 1 < n and texts[i + 1] == "[":
            body, after = attr_body(texts, i)
            if is_test_attr(body):
                start_line = lines[i]
                j = after
                path_attr = None
                while j < n and texts[j] == "#":  # more attributes
                    b2, j2 = attr_body(texts, j)
                    if b2[:1] == ["path"] and len(b2) >= 3:
                        path_attr = b2[2].strip('"')
                    j = j2
                # item: up to '{' or ';' at depth 0, or a '}' first (a struct field or a struct
                # literal's field, which ends at a ','; the span runs to the end of its struct)
                depth = 0
                k = j
                while k < n:
                    t = texts[k]
                    if t in ("(", "["):
                        depth += 1
                    elif t in (")", "]"):
                        depth -= 1
                    elif depth == 0 and t in ("{", ";", "}"):
                        break
                    k += 1
                if k >= n:
                    break
                if texts[k] == "}":
                    spans.append((start_line, lines[k]))
                    i = k
                    continue
                if texts[k] == ";":
                    if k >= 2 and texts[k - 2] == "mod":
                        mods.append((texts[k - 1], path_attr))
                    spans.append((start_line, lines[k]))
                    i = k + 1
                    continue
                end = match_close(texts, k, "{", "}")
                spans.append((start_line, lines[end]))
                i = end + 1
                continue
            i = after
            continue
        i += 1
    # merge
    spans.sort()
    merged: list[list[int]] = []
    for a, b in spans:
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return merged, mods


def feature_spans(texts: list[str], lines: list[int]):
    """[start, end, feature] of items under a positive `#[cfg(feature = "x")]` (also inside all(...))."""
    out = []
    n = len(texts)
    i = 0
    while i < n:
        if texts[i] == "#" and i + 1 < n and texts[i + 1] == "[":
            body, after = attr_body(texts, i)
            if body[:1] == ["cfg"] and "feature" in body and "not" not in body and "any" not in body:
                feat = body[body.index("feature") + 2].strip('"') if body.index("feature") + 2 < len(body) else "?"
                j = after
                while j < n and texts[j] == "#":
                    j = attr_body(texts, j)[1]
                depth = 0
                k = j
                while k < n:
                    t = texts[k]
                    if t in ("(", "["):
                        depth += 1
                    elif t in (")", "]"):
                        depth -= 1
                    elif depth == 0 and t in ("{", ";", "}"):
                        break
                    k += 1
                if k >= n:
                    break
                # A `}` first: the item was a struct field or a struct literal's field, which
                # ends at a `,`; the span runs to the end of its struct, not into what follows.
                end = k if texts[k] in (";", "}") else match_close(texts, k, "{", "}")
                out.append([lines[i], lines[end], feat])
                i = after
                continue
            i = after
            continue
        i += 1
    return out


def resolve_mod(parent: str, name: str, path_attr: str | None, files: set[str]) -> list[str]:
    d = os.path.dirname(parent)
    if path_attr:
        p = os.path.normpath(os.path.join(d, path_attr))
        return [p] if p in files else []
    base = os.path.basename(parent)
    stem = base[:-3]
    roots = [d] if base in ("mod.rs", "lib.rs", "main.rs") or base.endswith("_root.rs") else [os.path.join(d, stem), d]
    for r in roots:
        for c in (f"{r}/{name}.rs", f"{r}/{name}/mod.rs"):
            if c in files:
                return [c]
    return []


def in_spans(spans, line: int) -> bool:
    # spans: sorted list of [a, b]
    lo, hi = 0, len(spans)
    while lo < hi:
        mid = (lo + hi) // 2
        if spans[mid][1] < line:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(spans) and spans[lo][0] <= line


def area_of(path: str) -> str:
    p = path.split("/")
    if len(p) >= 3 and p[1] == "ts_goport" and p[2] == "src":
        top = p[3] if len(p) > 3 else ""
        return "ts_goport/" + (top[:-3] if top.endswith(".rs") else top)
    if len(p) >= 4 and p[1] == "ts_goport" and p[2] == "parts":
        return "ts_goport/parts/" + p[3]
    if len(p) >= 3 and p[1] == "ts_goport":
        return "ts_goport/" + p[2]
    return p[1] if len(p) > 1 else path


