def pctl(vals: list[int], p: float) -> float:
    if not vals:
        return 0
    s = sorted(vals)
    idx = min(len(s) - 1, max(0, int(round(p / 100 * (len(s) - 1)))))
    return s[idx]


DIAG_RE = re.compile(r"(STATS|_LOG|DUMP|TIMES|TRACE|DEBUG)$|_LOG_|CALL_LOG")
VERIFY_RE = re.compile(r"VERIFY|_CHECK$|_CHECK_|CHECK_VERSION")
TESTHOOK_RE = re.compile(r"_TEST_|_CHILD($|_)")


def hatch_class(h: dict) -> str:
    """By name and use (heuristic): test-hook, diagnostic, verification, tuning or behavior."""
    n = h["name"]
    if (not h["read_in_prod"] and h["features"]) or TESTHOOK_RE.search(n):
        return "test-hook"
    if DIAG_RE.search(n):
        return "diagnostic"
    if VERIFY_RE.search(n):
        return "verification"
    if not h["fallback"]:
        return "tuning"
    return "behavior"


def find_use_branches(an: dict, gates: dict):
    """For each gate (bool fn/static): (branch uses, other uses) in production code.

    A name defined once among prod fns/statics counts everywhere (not as a
    method: `.name(`); a common name (`enabled`) only in its own file or as
    `<module>::name`."""
    by_name: dict[str, list[str]] = defaultdict(list)
    for key, g in gates.items():
        by_name[g["name"]].append(key)
    defs = Counter()
    for a in an.values():
        if a["fkind"] == "prod":
            for f in a["funcs"]:
                defs[f["name"].split("::")[-1]] += 1
    res = {}
    for path, a in an.items():
        if a["fkind"] != "prod":
            continue
        texts, kinds, lines = a["texts"], a["kinds"], a["lines"]
        for i, t in enumerate(texts):
            if kinds[i] != K_ID or t not in by_name:
                continue
            if in_spans(a["spans"], lines[i]):
                continue
            nxt = texts[i + 1] if i + 1 < len(texts) else ""
            prv = texts[i - 1] if i else ""
            if prv == "fn" or prv in ("static", "const"):
                continue  # definition
            if prv == ".":
                continue  # a method of the same name
            key = None
            for k in by_name[t]:
                g = gates[k]
                if path == g["file"]:
                    key = k
                    break
                stem = os.path.basename(g["file"])[:-3]
                if stem == "mod":
                    stem = os.path.basename(os.path.dirname(g["file"]))
                if prv == "::" and i >= 2 and texts[i - 2] == stem:
                    key = k
                    break
                if defs[t] == 1 and len(by_name[t]) == 1:
                    key = k
            if key is None:
                continue
            if gates[key]["kind"] == "fn" and nxt != "(":
                continue  # a variable or field of the same name
            if gates[key]["kind"] == "static" and nxt == "(":
                continue
            pre = statement_prefix(texts, i)
            br = any(w in BRANCH_WORDS for w in pre) or prv in ("!",) and "if" in pre
            r = res.setdefault(key, {"branch": 0, "other": 0, "sites": [], "other_at": []})
            r["branch" if br else "other"] += 1
            if not br:
                r["other_at"].append((path, i, lines[i]))
            if len(r["sites"]) < 12:
                r["sites"].append(f"{path}:{lines[i]}")
    return res


def enclosing(funcs: list[dict], line: int):
    best = None
    for f in funcs:
        if f["start"] <= line <= f["end"] and (best is None or f["end"] - f["start"] < best["end"] - best["start"]):
            best = f
    return best


def fn_returns_bool(texts: list[str], lines: list[int], f: dict) -> bool:
    # find `fn name` at the function's start line and read the signature up to '{'
    short = f["name"].split("::")[-1]
    for i, ln in enumerate(lines):
        if ln < f["start"]:
            continue
        if ln > f["start"] + 3:
            break
        if texts[i] == "fn" and i + 1 < len(texts) and texts[i + 1] == short:
            j = i + 2
            while j < len(texts) and texts[j] not in ("{", ";"):
                j += 1
            sig = texts[i:j]
            if "->" in sig:
                ret = sig[sig.index("->") + 1 :]
                return ret[-1:] == ["bool"] or ret[:1] == ["bool"]
            return False
    return False


def static_holder(texts: list[str], tok: int):
    """Name of a `static`/`const` item whose initializer holds token tok (top-level LazyLock etc.)."""
    depth = 0
    j = tok
    while j >= 0:
        t = texts[j]
        if t in ("}", ")", "]"):
            depth += 1
        elif t in ("{", "(", "["):
            depth -= 1
        elif t == ";" and depth <= 0:
            return None
        if t in ("static", "const") and depth <= 0 and j + 1 < len(texts):
            k = j + 1
            if texts[k] == "mut":
                k += 1
            nm = texts[k]
            # the item's type, up to `=`: a switch only when it holds a bool
            ty = []
            m = k + 2
            while m < len(texts) and texts[m] != "=":
                ty.append(texts[m])
                m += 1
            return nm if "bool" in ty else None
        if t == "fn" and depth < 0:
            return None
        j -= 1
    return None


def build_snapshot(sha: str, with_clippy: bool) -> dict:
    tree = crates_tree(sha)
    cache = CACHE / "snap" / f"{tree}-v{VERSION}.json"
    snap = None
    if cache.exists():
        snap = json.loads(cache.read_text())
    else:
        snap = measure_tree(sha, tree)
        cache.parent.mkdir(parents=True, exist_ok=True)
        tmp = cache.with_suffix(".tmp")
        tmp.write_text(json.dumps(snap))
        tmp.replace(cache)
    snap["sha"] = sha
    if with_clippy:
        snap["clippy"] = clippy_counts(sha)
    return snap


def measure_tree(sha: str, tree: str) -> dict:
    t0 = time.time()
    (CACHE / "tmp").mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="q-", dir=CACHE / "tmp"))
    try:
        src_root = work / "src"
        src_root.mkdir()
        arch = subprocess.run(["git", "archive", "--format=tar", sha, "crates"], cwd=REPO, check=True, capture_output=True).stdout
        subprocess.run(["tar", "-x", "-C", str(src_root)], input=arch, check=True)
        files = sorted(str(p.relative_to(src_root)) for p in (src_root / "crates").rglob("*.rs"))
        fileset = set(files)
        rca_out = work / "rca"
        rca_out.mkdir()
        if not RCA.exists():
            sys.exit(f"rust-code-analysis-cli not found at {RCA}; run `quality.sh install`")
        subprocess.run([str(RCA), "-m", "-p", "crates", "-I", "*.rs", "-O", "json", "-j", str(min(16, os.cpu_count() or 4)),
                        "-o", str(rca_out)], cwd=src_root, check=True, capture_output=True)
        an: dict[str, dict] = {}
        for path in files:
            src = (src_root / path).read_text(errors="replace")
            head = "\n".join(src.split("\n", 15)[:15])
            if is_generated(path, head):
                fk = "generated"
            else:
                fk = classify_path(path) or "prod"
            a = analyze_file(path, src, "test" if fk == "test" else "prod")
            a["fkind"] = fk
            an[path] = a
        # `#[cfg(test)] mod x;` files are test files
        changed = True
        while changed:
            changed = False
            for path, a in list(an.items()):
                for name, pattr in a["mods"]:
                    for c in resolve_mod(path, name, pattr, fileset):
                        if an[c]["fkind"] == "prod":
                            src = (src_root / c).read_text(errors="replace")
                            b = analyze_file(c, src, "test")
                            b["fkind"] = "test"
                            an[c] = b
                            changed = True
                        # its child module dir is test too
                        sub = c[:-3] + "/" if not c.endswith("/mod.rs") else c[: -len("mod.rs")]
                        for other in files:
                            if other.startswith(sub) and an[other]["fkind"] == "prod":
                                src = (src_root / other).read_text(errors="replace")
                                b = analyze_file(other, src, "test")
                                b["fkind"] = "test"
                                an[other] = b
                                changed = True
        for path, a in an.items():
            a["funcs"] = rca_functions(rca_out, src_root, path)

        default_features: set[str] = set()
        for toml in (src_root / "crates").rglob("Cargo.toml"):
            m = re.search(r"^default\s*=\s*\[([^\]]*)\]", toml.read_text(), re.M)
            if m:
                default_features.update(x.strip().strip('"') for x in m.group(1).split(",") if x.strip())
        snap = summarize(sha, tree, an, default_features)
        snap["default_features"] = sorted(default_features)
        snap["measure_seconds"] = round(time.time() - t0, 1)
        return snap
    finally:
        shutil.rmtree(work, ignore_errors=True)


def summarize(sha: str, tree: str, an: dict, default_features: set[str]) -> dict:
    files_out = {}
    totals = Counter()
    areas: dict[str, Counter] = defaultdict(Counter)
    hyg_total = {"prod": Counter(), "test": Counter()}
    hyg_files: dict[str, dict] = {}
    allow_total = {"prod": Counter(), "test": Counter()}
    funcs_out = []
    for path, a in an.items():
        fk = a["fkind"]
        files_out[path] = {"kind": fk, "spans": a["spans"]}
        if fk == "generated":
            totals["files_generated"] += 1
            totals["lines_generated"] += a["nlines"]
            continue
        totals["files_" + fk] += 1
        totals["code_prod"] += a["code_prod"]
        totals["code_test"] += a["code_test"]
        ar = area_of(path)
        areas[ar]["code_prod"] += a["code_prod"]
        areas[ar]["code_test"] += a["code_test"]
        for s in ("prod", "test"):
            hyg_total[s].update(a["hyg"][s])
            allow_total[s].update(a["allow_lints"][s])
        if a["hyg"]["prod"]:
            hyg_files[path] = dict(a["hyg"]["prod"])
            for k2, v in a["hyg"]["prod"].items():
                areas[ar]["hyg_" + k2] += v
        for f in a["funcs"]:
            test = fk == "test" or in_spans(a["spans"], f["start"])
            funcs_out.append({"file": path, **f, "test": test})
            if not test:
                areas[ar]["fn_prod"] += 1
                if f["cog"] > COG_THRESHOLDS[0]:
                    areas[ar]["fn_cog_gt25"] += 1

    # function name disambiguation (same file+name)
    seen = Counter()
    for f in funcs_out:
        key = f"{f['file']}::{f['name']}"
        seen[key] += 1
        f["key"] = key if seen[key] == 1 else f"{key}#{seen[key]}"

    prod_fns = [f for f in funcs_out if not f["test"]]
    test_fns = [f for f in funcs_out if f["test"]]

    def dist(fns):
        cog = [f["cog"] for f in fns]
        cyc = [f["cyc"] for f in fns]
        return {
            "count": len(fns),
            "cog": {"p50": pctl(cog, 50), "p90": pctl(cog, 90), "p99": pctl(cog, 99), "max": max(cog, default=0),
                    "sum": sum(cog), **{f"gt{t}": sum(1 for c in cog if c > t) for t in COG_THRESHOLDS}},
            "cyc": {"p50": pctl(cyc, 50), "p90": pctl(cyc, 90), "p99": pctl(cyc, 99), "max": max(cyc, default=0),
                    **{f"gt{t}": sum(1 for c in cyc if c > t) for t in CYC_THRESHOLDS}},
        }

    # escape hatches
    const_defs = {}
    for path, a in an.items():
        if a["fkind"] == "prod":
            for k2, v in a["const_defs"].items():
                const_defs[k2] = v
    sites = []
    for path, a in an.items():
        if a["fkind"] != "prod":
            continue
        for s in a["env_sites"]:
            sites.append({**s, "file": path})
        # const uses
        if const_defs:
            texts, kinds, lines = a["texts"], a["kinds"], a["lines"]
            for i, t in enumerate(texts):
                if kinds[i] == K_ID and t in const_defs:
                    prv = texts[i - 1] if i else ""
                    if prv in ("const", "static") or in_spans(a["spans"], lines[i]):
                        continue
                    site = {"name": const_defs[t], "line": lines[i], "tok": i, "file": path,
                            "kind": env_site_kind(texts, i), "via": t}
                    for fa, fb, ft in a["fspans"]:
                        if fa <= lines[i] <= fb:
                            site["feature"] = ft
                    sites.append(site)
    gates: dict[str, dict] = {}
    for s in sites:
        if s["kind"] not in ("read", "compile"):
            continue
        a = an[s["file"]]
        f = enclosing(a["funcs"], s["line"])
        holder = None
        if f is not None and fn_returns_bool(a["texts"], a["lines"], f):
            holder = ("fn", f["name"].split("::")[-1])
        elif f is None:
            st = static_holder(a["texts"], s["tok"])
            if st:
                holder = ("static", st)
        pre = statement_prefix(a["texts"], s["tok"])
        # a parsed value (`if let Some(n) = env::var(..).ok().and_then(|v| v.parse().ok())`) is a
        # tuning knob, not a path switch; option_env! is a build-time value
        knob = "parse" in statement_suffix(a["texts"], s["tok"]) or s["kind"] == "compile"
        s["direct_branch"] = any(w in BRANCH_WORDS for w in pre) and holder is None and not knob
        s["fn"] = f["name"] if f else None
        if holder:
            key = f"{holder[1]}@{s['file']}"
            s["gate"] = key
            gates.setdefault(key, {"kind": holder[0], "name": holder[1], "names": set(), "file": s["file"]})["names"].add(s["name"])
    uses = find_use_branches(an, gates)
    # gate chains: a bool fn that returns a gate's value (`fn plain_early_emit() -> bool { enabled() && .. }`)
    # is a gate too, for the same env names (3 levels)
    for _ in range(3):
        added = False
        for key, u in list(uses.items()):
            for path, tok, line in u.get("other_at", []):
                a = an[path]
                f = enclosing(a["funcs"], line)
                if f is None or not fn_returns_bool(a["texts"], a["lines"], f):
                    continue
                k2 = f"{f['name'].split('::')[-1]}@{path}"
                if k2 in gates:
                    gates[k2]["names"] |= gates[key]["names"]
                    continue
                gates[k2] = {"kind": "fn", "name": f["name"].split("::")[-1], "names": set(gates[key]["names"]),
                             "file": path, "via": key}
                added = True
        if not added:
            break
        uses = find_use_branches(an, gates)
    hatches: dict[str, dict] = {}
    for s in sites:
        h = hatches.setdefault(s["name"], {"name": s["name"], "files": set(), "reads": 0, "sets": 0, "defs": 0,
                                           "direct_branches": 0, "gates": set(), "sites": [], "shipped_reads": 0,
                                           "features": set()})
        h["files"].add(s["file"])
        if s["kind"] in ("read", "compile"):
            h["reads"] += 1
            if s.get("feature") and s["feature"] not in default_features:
                h["features"].add(s["feature"])
            else:
                h["shipped_reads"] += 1
            if s.get("direct_branch"):
                h["direct_branches"] += 1
            if s.get("gate"):
                h["gates"].add(s["gate"])
        elif s["kind"] == "set":
            h["sets"] += 1
        else:
            h["defs"] += 1
        h["sites"].append(f"{s['file']}:{s['line']}:{s['kind']}" + (f" ({s['fn']})" if s.get("fn") else ""))
    for key, g in gates.items():
        for n in g["names"]:
            if n in hatches:
                hatches[n]["gates"].add(key)
    for u in uses.values():
        u.pop("other_at", None)
    hatch_list = []
    for h in sorted(hatches.values(), key=lambda x: x["name"]):
        gate_branch = sum(uses.get(g, {}).get("branch", 0) for g in h["gates"])
        hatch_list.append({
            **h, "files": sorted(h["files"]), "gates": sorted(h["gates"]), "features": sorted(h["features"]),
            "gate_branch_uses": gate_branch,
            "gate_uses": sum(uses.get(g, {}).get("branch", 0) + uses.get(g, {}).get("other", 0) for g in h["gates"]),
            # a switch: read into a bool gate (fn or static) or branched on where it is read
            "fallback": h["shipped_reads"] > 0 and (h["direct_branches"] > 0 or bool(h["gates"])),
            # read in a default build (not only under a non-default cargo feature such as test-hooks)
            "read_in_prod": h["shipped_reads"] > 0,
        })
        hatch_list[-1]["class"] = hatch_class(hatch_list[-1])
    gate_list = {g: {"kind": v["kind"], "name": v["name"], "file": v["file"], "env": sorted(v["names"]), "via": v.get("via"),
                     **uses.get(g, {"branch": 0, "other": 0, "sites": []})}
                 for g, v in gates.items()}
    features = Counter()
    feature_sites = defaultdict(list)
    for path, a in an.items():
        if a["fkind"] == "prod":
            for ft in a["features"]:
                features[ft["feature"]] += 1
                if len(feature_sites[ft["feature"]]) < 8:
                    feature_sites[ft["feature"]].append(f"{path}:{ft['line']}")

    # duplication
    intern: dict[str, int] = {}
    dfiles = []
    texts_ref = []
    tfiles = []
    for path in sorted(an):
        a = an[path]
        if a["fkind"] == "generated":
            continue
        ids = array("i")
        lns = []
        tex = []
        for t, ln in zip(a["texts"], a["lines"]):
            test = a["fkind"] == "test" or in_spans(a["spans"], ln)
            if test:
                continue
            ids.append(intern.setdefault(t, len(intern)))
            lns.append(ln)
            tex.append(t)
        if len(ids):
            dfiles.append((path, ids, lns))
            texts_ref.append(tex)
    blocks, dup_lines = find_clones(dfiles, DUP_MIN_TOKENS, DUP_MIN_LINES, lambda fi, a0, a1: texts_ref[fi][a0:a1])
    prod_code_lines = 0
    dup_code = 0
    dup_by_file = {}
    for (path, ids, lns) in dfiles:
        ls = set(lns)
        prod_code_lines += len(ls)
        d = len(ls & dup_lines.get(path, set()))
        dup_code += d
        if d:
            dup_by_file[path] = d
    for p, c in dup_by_file.items():
        areas[area_of(p)]["dup_lines"] += c

    # drop heavy fields
    return {
        "version": VERSION, "tree": tree, "sha": sha,
        "totals": dict(totals),
        "areas": {k: dict(v) for k, v in sorted(areas.items())},
        "functions": {"prod": dist(prod_fns), "test": dist(test_fns)},
        "funcs": [{k: f[k] for k in ("key", "file", "name", "start", "end", "cyc", "cog", "sloc", "test")} for f in funcs_out if not f["test"]],
        "hygiene": {s: dict(hyg_total[s]) for s in hyg_total},
        "hygiene_files": hyg_files,
        "allow_lints": {s: dict(allow_total[s].most_common()) for s in allow_total},
        "hatches": hatch_list,
        "gates": gate_list,
        "features": {k: {"count": v, "sites": feature_sites[k]} for k, v in sorted(features.items())},
        "dup": {"min_tokens": DUP_MIN_TOKENS, "min_lines": DUP_MIN_LINES, "prod_code_lines": prod_code_lines,
                "dup_lines": dup_code, "pct": round(100 * dup_code / max(1, prod_code_lines), 2),
                "blocks": sorted(blocks, key=lambda b: -b["tokens"]), "by_file": dup_by_file},
        "files": files_out,
    }


