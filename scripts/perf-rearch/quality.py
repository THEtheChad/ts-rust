PANIC_MACROS = ("panic", "unreachable", "todo", "unimplemented")
SET_METHODS = ("env", "env_remove", "set_var", "remove_var")


def statement_prefix(texts: list[str], i: int) -> list[str]:
    """Tokens from the start of the statement or condition holding token i."""
    depth = 0
    j = i - 1
    while j >= 0:
        t = texts[j]
        if t in (")", "]"):
            depth += 1
        elif t in ("(", "["):
            depth -= 1
        elif t in (";", "{", "}") and depth <= 0:
            break
        j -= 1
    return texts[j + 1 : i]


def statement_suffix(texts: list[str], i: int) -> list[str]:
    """Tokens after token i up to the end of its expression (`;` or a block `{` at depth 0)."""
    depth = 0
    j = i + 1
    while j < len(texts):
        t = texts[j]
        if t in ("(", "["):
            depth += 1
        elif t in (")", "]"):
            depth -= 1
            if depth < 0:
                depth = 0
        elif t in (";", "{", "}") and depth == 0:
            break
        j += 1
    return texts[i + 1 : j]


BRANCH_WORDS = {"if", "while", "match", "&&", "||", "?", "then", "then_some", "filter", "unwrap_or_else", "is_some_and", "is_none_or"}


def env_site_kind(texts: list[str], i: int) -> str:
    """Kind of a string literal / const use naming an env var: read, set, compile, def."""
    # walk back over the call: `X(` ... literal
    j = i - 1
    if j >= 0 and texts[j] == "(":
        f = texts[j - 1] if j >= 1 else ""
        if f in SET_METHODS:
            return "set"
        if f == "!" and j >= 2 and texts[j - 2] == "option_env":
            return "compile"
        if f == "!" and j >= 2 and texts[j - 2] in ("env",):
            return "compile"
    if j >= 1 and texts[j] == "=" and i + 1 < len(texts) and texts[i + 1] == ";":
        pre = statement_prefix(texts, i)
        if pre and pre[0] in ("const", "static", "pub") and ("const" in pre or "static" in pre):
            return "def"
    pre = statement_prefix(texts, i)
    if "env" in pre and any(t in pre for t in ("set_var", "remove_var")):
        return "set"
    if "Command" in pre or ".env(" in "".join(pre[-3:]):
        return "set"
    return "read"


def analyze_file(path: str, src: str, kind: str, spans_hint=None):
    kinds, texts, lines, comments = lex(src)
    spans, mods = test_spans(texts, lines)
    fspans = feature_spans(texts, lines)
    if kind == "test":
        spans = [[1, max(lines[-1] if lines else 1, src.count("\n") + 1)]]
    nlines = src.count("\n") + 1

    def is_test(line: int) -> bool:
        return kind == "test" or in_spans(spans, line)

    code_lines = {"prod": set(), "test": set()}
    for ln in lines:
        code_lines["test" if is_test(ln) else "prod"].add(ln)

    hyg = {s: Counter() for s in ("prod", "test")}
    allow_lints = {s: Counter() for s in ("prod", "test")}
    env_sites: list[dict] = []
    const_defs: dict[str, str] = {}
    features: list[dict] = []
    n = len(texts)
    for i, t in enumerate(texts):
        k = kinds[i]
        if k == K_ID:
            if t == "unsafe":
                s = "test" if is_test(lines[i]) else "prod"
                hyg[s]["unsafe"] += 1
                if i + 1 < n and texts[i + 1] == "{":
                    hyg[s]["unsafe_block"] += 1
            elif t in ("unwrap", "expect") and i >= 1 and texts[i - 1] == "." and i + 1 < n and texts[i + 1] == "(":
                if t == "expect" or (i + 2 < n and texts[i + 2] == ")"):
                    s = "test" if is_test(lines[i]) else "prod"
                    hyg[s][t] += 1
            elif t in PANIC_MACROS and i + 1 < n and texts[i + 1] == "!":
                s = "test" if is_test(lines[i]) else "prod"
                hyg[s][t + "!"] += 1
            elif t == "feature" and i + 2 < n and texts[i + 1] == "=" and kinds[i + 2] == K_STR:
                pre = texts[max(0, i - 6) : i]
                if "cfg" in pre or "cfg_attr" in pre or "any" in pre or "all" in pre or "not" in pre:
                    if not is_test(lines[i]):
                        features.append({"feature": texts[i + 2].strip('"'), "line": lines[i]})
        elif k == K_P and t == "#":
            j = i + 1
            if j < n and texts[j] == "!":
                j += 1
            if j + 1 < n and texts[j] == "[" and texts[j + 1] in ("allow", "expect") and j + 2 < n and texts[j + 2] == "(":
                s = "test" if is_test(lines[i]) else "prod"
                hyg[s]["allow_attr" if texts[j + 1] == "allow" else "expect_attr"] += 1
                end = match_close(texts, j + 2, "(", ")")
                body = "".join(texts[j + 3 : end])
                for lint in body.split(","):
                    if lint:
                        allow_lints[s][lint] += 1
        elif k == K_STR:
            v = t
            if v.startswith('"') and v.endswith('"') and HATCH_RE.match(v[1:-1]):
                name = v[1:-1]
                if is_test(lines[i]):
                    continue
                sk = env_site_kind(texts, i)
                if sk == "def":
                    pre = statement_prefix(texts, i)
                    for a, b in zip(pre, pre[1:]):
                        if a in ("const", "static"):
                            const_defs[b] = name
                            break
                site = {"name": name, "line": lines[i], "tok": i, "kind": sk}
                for fa, fb, ft in fspans:
                    if fa <= lines[i] <= fb:
                        site["feature"] = ft
                env_sites.append(site)
    for ln, text in comments:
        s = "test" if is_test(ln) else "prod"
        for m in MARKER_RE.finditer(text):
            hyg[s][m.group(1)] += 1
    comment_lines = {ln for ln, _ in comments}
    return {
        "kinds": kinds, "texts": texts, "lines": lines, "spans": spans, "mods": mods,
        "nlines": nlines, "code_prod": len(code_lines["prod"]), "code_test": len(code_lines["test"]),
        "comment_lines": len(comment_lines), "hyg": hyg, "allow_lints": allow_lints,
        "env_sites": env_sites, "const_defs": const_defs, "features": features, "fspans": fspans,
        "test_line_set": None,
    }


