def rca_functions(rca_dir: Path, root: Path, path: str):
    f = rca_dir / root.name / (path + ".json")
    if not f.exists():
        # rca writes <out>/<input path relative>; find by suffix
        cands = list(rca_dir.rglob(path.split("/")[-1] + ".json"))
        cands = [c for c in cands if str(c).endswith(path + ".json")]
        if not cands:
            return []
        f = cands[0]
    d = json.loads(f.read_text())
    out = []

    def walk(space, scope):
        for s in space.get("spaces", []):
            kind = s["kind"]
            name = s.get("name") or "<anon>"
            if kind == "function" and name == "<anonymous>":
                walk(s, scope)  # a closure: its metrics are already in the enclosing function's sums
            elif kind == "function":
                m = s["metrics"]
                out.append({
                    "name": "::".join(scope + [name]), "start": s["start_line"], "end": s["end_line"],
                    "cyc": int(m["cyclomatic"]["sum"]), "cog": int(m["cognitive"]["sum"]),
                    "sloc": int(m["loc"]["sloc"]),
                })
                walk(s, scope + [name])
            elif kind in ("impl", "trait", "struct", "namespace"):
                walk(s, scope + [name])
            else:
                walk(s, scope)

    walk(d, [])
    return out


