def delta(base: dict, rev: dict) -> dict:
    d: dict = {"base": base["sha"][:9], "rev": rev["sha"][:9]}
    d["churn"] = churn(base, rev) if base["tree"] != rev["tree"] else {"prod_add": 0, "prod_del": 0, "test_add": 0, "test_del": 0,
                                                                        "prod_net": 0, "test_net": 0, "files_touched": 0,
                                                                        "files_prod": 0, "files_test": 0, "generated_add": 0,
                                                                        "generated_del": 0, "test_to_prod_add": 0, "prod_net_by_file": {}}
    bt, rt = base["totals"], rev["totals"]
    d["code_prod"] = rt.get("code_prod", 0) - bt.get("code_prod", 0)
    d["code_test"] = rt.get("code_test", 0) - bt.get("code_test", 0)
    # hatches
    bh = {h["name"]: h for h in base["hatches"]}
    rh = {h["name"]: h for h in rev["hatches"]}
    d["hatches_new"] = [rh[n] for n in sorted(set(rh) - set(bh))]
    d["hatches_removed"] = sorted(set(bh) - set(rh))
    d["hatches_changed"] = []
    for n in sorted(set(bh) & set(rh)):
        a, b = bh[n], rh[n]
        if (a["reads"], a["direct_branches"], a["gate_branch_uses"], a["sets"]) != (b["reads"], b["direct_branches"], b["gate_branch_uses"], b["sets"]):
            d["hatches_changed"].append({"name": n, "reads": [a["reads"], b["reads"]],
                                         "direct_branches": [a["direct_branches"], b["direct_branches"]],
                                         "gate_branch_uses": [a["gate_branch_uses"], b["gate_branch_uses"]],
                                         "sets": [a["sets"], b["sets"]], "new_sites": sorted(set(b["sites"]) - set(a["sites"]))[:10]})
    d["hatch_classes"] = {c: [sum(1 for h in base["hatches"] if h["class"] == c), sum(1 for h in rev["hatches"] if h["class"] == c)]
                          for c in ("behavior", "tuning", "diagnostic", "verification", "test-hook")}
    d["hatch_counts"] = {"base": sum(1 for h in base["hatches"] if h["read_in_prod"]), "rev": sum(1 for h in rev["hatches"] if h["read_in_prod"]),
                         "fallback_base": sum(1 for h in base["hatches"] if h["fallback"]),
                         "fallback_rev": sum(1 for h in rev["hatches"] if h["fallback"])}
    bg, rg = base["gates"], rev["gates"]
    d["gates_branch"] = {"base": sum(g["branch"] for g in bg.values()), "rev": sum(g["branch"] for g in rg.values())}
    d["features_new"] = sorted(set(rev["features"]) - set(base["features"]))
    # functions
    bf = {f["key"]: f for f in base["funcs"]}
    rf = {f["key"]: f for f in rev["funcs"]}
    grown = []
    for k, f in rf.items():
        o = bf.get(k)
        oc = o["cog"] if o else 0
        if f["cog"] - oc >= 5 or (o is None and f["cog"] > COG_THRESHOLDS[0]):
            grown.append({"key": k, "cog": [o["cog"] if o else None, f["cog"]], "cyc": [o["cyc"] if o else None, f["cyc"]],
                          "sloc": [o["sloc"] if o else None, f["sloc"]]})
    grown.sort(key=lambda g: -(g["cog"][1] - (g["cog"][0] or 0)))
    d["functions_grown"] = grown[:20]
    d["functions_grown_count"] = len(grown)
    d["functions_new"] = len(set(rf) - set(bf))
    d["functions_removed"] = len(set(bf) - set(rf))
    bp, rp = base["functions"]["prod"], rev["functions"]["prod"]
    d["functions"] = {k: [bp["cog"][k], rp["cog"][k]] for k in ("p50", "p90", "p99", "max", "gt25", "gt50", "sum")}
    d["functions"]["count"] = [bp["count"], rp["count"]]
    d["functions"]["cyc_gt25"] = [bp["cyc"]["gt25"], rp["cyc"]["gt25"]]
    # duplication
    bb = {b["id"] for b in base["dup"]["blocks"]}
    newb = [b for b in rev["dup"]["blocks"] if b["id"] not in bb]
    d["dup"] = {"pct": [base["dup"]["pct"], rev["dup"]["pct"]], "lines": [base["dup"]["dup_lines"], rev["dup"]["dup_lines"]],
                "blocks": [len(base["dup"]["blocks"]), len(rev["dup"]["blocks"])], "new_blocks": newb[:15], "new_block_count": len(newb)}
    # hygiene
    keys = sorted(set(base["hygiene"]["prod"]) | set(rev["hygiene"]["prod"]))
    d["hygiene"] = {k: [base["hygiene"]["prod"].get(k, 0), rev["hygiene"]["prod"].get(k, 0)] for k in keys}
    hf = Counter()
    for p, v in rev["hygiene_files"].items():
        o = base["hygiene_files"].get(p, {})
        for k2 in ("unwrap", "expect", "allow_attr", "TODO", "FIXME", "HACK", "XXX", "unsafe"):
            x = v.get(k2, 0) - o.get(k2, 0)
            if x:
                hf[f"{p} {k2}"] += x
    d["hygiene_file_changes"] = dict(sorted(hf.items(), key=lambda kv: -abs(kv[1]))[:15])
    if "clippy" in base and "clippy" in rev:
        d["clippy"] = {}
        for name in ("config", "forced"):
            bl, rl = base["clippy"][name].get("by_lint", {}), rev["clippy"][name].get("by_lint", {})
            ch = {k: rl.get(k, 0) - bl.get(k, 0) for k in set(bl) | set(rl)}
            bfl, rfl = base["clippy"][name].get("by_file", {}), rev["clippy"][name].get("by_file", {})
            d["clippy"][name] = {"total": [base["clippy"][name]["total"], rev["clippy"][name]["total"]],
                                 "by_lint_delta": dict(sorted(((k, v) for k, v in ch.items() if v), key=lambda kv: -abs(kv[1]))[:15]),
                                 "by_file_delta": dict(sorted(((k, rfl.get(k, 0) - bfl.get(k, 0)) for k in set(bfl) | set(rfl)
                                                               if rfl.get(k, 0) != bfl.get(k, 0)), key=lambda kv: -abs(kv[1]))[:10])}
    return d


