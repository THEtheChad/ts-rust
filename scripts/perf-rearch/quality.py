# escape hatches, from rustc's cfg-expanded source (qexpand.py)
#
# Which code ships is rustc's answer, not ours: the inventory reads the pieces of the expanded
# `default` build (shipped) and of the `features` build (default + diagnostics,test-hooks). A name
# read in the features build and not in the default one is "only under a feature". No cfg
# attribute is parsed here. Lines are mapped back to the source file of each piece
# (`map_source_lines`) for the report only.


def fn_spans(kinds: list[int], texts: list[str], lines: list[int]) -> list[dict]:
    """The functions of compiler-printed source: `fn name ... { body }` (start and end lines).
    A `fn` with no body (`;`) or a `fn(..)` pointer type is not one."""
    funcs = []
    n = len(texts)
    for i, t in enumerate(texts):
        if t != "fn" or kinds[i] != K_ID or i + 1 >= n or kinds[i + 1] != K_ID:
            continue
        depth = 0
        j = i + 2
        while j < n:
            u = texts[j]
            if u in ("(", "["):
                depth += 1
            elif u in (")", "]"):
                depth -= 1
            elif depth == 0 and u == ";":
                break
            elif depth == 0 and u == "{":
                end = match_close(texts, j, "{", "}")
                funcs.append({"name": texts[i + 1], "start": lines[i], "end": lines[end]})
                break
            j += 1
    return funcs


def analyze_piece(text: str) -> dict:
    kinds, texts, lines, _ = lex(text)
    sites = []
    const_defs: dict[str, str] = {}
    for i, t in enumerate(texts):
        if kinds[i] == K_STR and t.startswith('"') and t.endswith('"') and HATCH_RE.match(t[1:-1]):
            name = t[1:-1]
            sk = env_site_kind(texts, i)
            if sk == "def":
                pre = statement_prefix(texts, i)
                for a, b in zip(pre, pre[1:]):
                    if a in ("const", "static"):
                        const_defs[b] = name
                        break
            sites.append({"name": name, "line": lines[i], "tok": i, "kind": sk, "text": t})
    return {"kinds": kinds, "texts": texts, "lines": lines,
            "funcs": fn_spans(kinds, texts, lines), "env_sites": sites, "const_defs": const_defs}


def map_source_lines(pa: dict, src: dict | None, sites: list[dict]) -> None:
    """Sets `src_line` (and `approx`) on each site of one piece: the line of the same token in the
    piece's source file. Equal counts of the token in piece and file pair them in order (exact);
    otherwise sites are paired within the source function of the same name, in order, and marked
    approximate. Report only: nothing decides on these lines."""
    if src is None:
        for s in sites:
            s["src_line"], s["approx"] = None, True
        return
    by_tok: dict[str, list[dict]] = defaultdict(list)
    for s in sites:
        by_tok[s["text"]].append(s)
    st = src["texts"]
    for tok, ss in by_tok.items():
        # a const's own definition is no site (as in `inventory_of`)
        occ = [ln for j, (t, ln) in enumerate(zip(st, src["lines"])) if t == tok and (j == 0 or st[j - 1] not in ("const", "static"))]
        # a `{NAME}` capture of a format string is a token only after expansion
        core = [s for s in ss if s["kind"] != "mention"]
        if len(occ) == len(core):
            for s, ln in zip(core, occ):
                s["src_line"], s["approx"] = ln, False
            ss = [s for s in ss if s["kind"] == "mention"]
        used: set[int] = set()
        for s in ss:
            f = enclosing(pa["funcs"], s["line"])
            cands = [ln for ln in occ if ln not in used]
            if f is not None:
                fs = [g for g in src["funcs"] if g["name"].split("::")[-1] == f["name"]]
                inside = [ln for ln in cands if any(g["start"] <= ln <= g["end"] for g in fs)]
                cands = inside or cands
            s["src_line"], s["approx"] = (cands[0], True) if cands else (None, True)
            if cands:
                used.add(cands[0])


class Pieces:
    """The pieces of one expanded build by key (the source file; `file#modpath` for a second
    module of the same file), analyzed (`analyze_piece`) on first access: lexing all 60 MB of
    expanded source takes 40 s, and only pieces naming a hatch, a hatch const or a gate matter."""

    FN_RE = re.compile(r"\bfn (?:r#)?([A-Za-z_][A-Za-z0-9_]*)")  # rustc prints one space

    def __init__(self, pieces: list[dict]):
        self.text: dict[str, str] = {}
        self.src: dict[str, str] = {}
        for p in pieces:
            key = p["file"] if p["file"] not in self.text else f"{p['file']}#{p['modpath']}"
            self.text[key] = p["text"]
            self.src[key] = p["file"]
        self.done: dict[str, dict] = {}
        self.defs = Counter(m.group(1) for t in self.text.values() for m in self.FN_RE.finditer(t))

    def __getitem__(self, key: str) -> dict:
        a = self.done.get(key)
        if a is None:
            a = analyze_piece(self.text.get(key, ""))
            a["src_file"] = self.src.get(key, key)
            self.done[key] = a
        return a

    def __contains__(self, key: str) -> bool:
        return key in self.text

    def ensure(self, key: str) -> None:
        self.text.setdefault(key, "")
        self.src.setdefault(key, key)

    def keys_with(self, words: set[str] | None) -> list[str]:
        """Keys of the pieces whose text has one of `words` as a word (None: a hatch name)."""
        if words is not None and not words:
            return []
        subs = ("GOPORT_", "TSC_RS_", "TSGO_") if words is None else tuple(words)
        rx = re.compile(r"(GOPORT|TSC_RS|TSGO)_[A-Z0-9_]" if words is None else
                        r"\b(?:" + "|".join(map(re.escape, sorted(words))) + r")\b")
        return [k for k, t in self.text.items() if any(w in t for w in subs) and rx.search(t)]


def inventory_of(exp: dict, src_an: dict) -> tuple[dict, dict]:
    """Escape hatches and bool gates of one expanded build: ({name: hatch}, {gate key: gate})."""
    an = Pieces(exp["pieces"])
    hatch_keys = an.keys_with(None)
    const_defs = {}
    for k in hatch_keys:
        const_defs.update(an[k]["const_defs"])
    sites = []
    for path in sorted(set(hatch_keys) | set(an.keys_with(set(const_defs)))):
        a = an[path]
        ps = [{**s, "file": path} for s in a["env_sites"]]
        if const_defs:
            texts, kinds, lines = a["texts"], a["kinds"], a["lines"]
            for i, t in enumerate(texts):
                if kinds[i] == K_ID and t in const_defs and (texts[i - 1] if i else "") not in ("const", "static"):
                    ps.append({"name": const_defs[t], "line": lines[i], "tok": i, "file": path, "text": t,
                               "kind": env_site_kind(texts, i), "via": t})
        map_source_lines(a, src_an.get(a["src_file"]), ps)
        sites += ps
    # env!/option_env! names: rustc's dep-info has them (the expanded source holds only the value)
    for c in exp["crates"]:
        for name in c["env_deps"]:
            if not HATCH_RE.match(name):
                continue
            where = [(f, ln) for f in c["files"] if f in src_an
                     for t, ln in zip(src_an[f]["texts"], src_an[f]["lines"]) if t == f'"{name}"']
            f, ln = where[0] if where else (c["root"], None)
            an.ensure(f)
            sites.append({"name": name, "line": 0, "tok": None, "file": f, "kind": "compile", "src_line": ln,
                          "approx": len(where) != 1})
    gates: dict[str, dict] = {}
    for s in sites:
        if s["kind"] not in ("read", "compile"):
            continue
        a = an[s["file"]]
        if s["tok"] is None:  # an env! name: a build-time value
            s["direct_branch"], s["fn"] = False, None
            continue
        f = enclosing(a["funcs"], s["line"])
        holder = None
        if f is not None and fn_returns_bool(a["texts"], a["lines"], f):
            holder = ("fn", f["name"].split("::")[-1])
        elif f is None:
            st = static_holder(a["texts"], s["tok"])
            if st:
                holder = ("static", st)
        pre = statement_prefix(a["texts"], s["tok"])
        # a parsed value (`if let Some(n) = env::var(..).ok().and_then(|v| v.parse().ok())`) is a
        # tuning knob, not a path switch
        knob = "parse" in statement_suffix(a["texts"], s["tok"])
        s["direct_branch"] = any(w in BRANCH_WORDS for w in pre) and holder is None and not knob
        s["fn"] = f["name"] if f else None
        if holder:
            key = f"{holder[1]}@{s['file']}"
            s["gate"] = key
            gates.setdefault(key, {"kind": holder[0], "name": holder[1], "names": set(), "file": s["file"]})["names"].add(s["name"])
    uses = find_use_branches(an, gates, an.defs)
    # gate chains: a bool fn that returns a gate's value (`fn plain_early_emit() -> bool { enabled() && .. }`)
    # is a gate too, for the same env names (3 levels)
    for _ in range(3):
        added = False
        for key, u in list(uses.items()):
            for path, tok, line in u.get("other_at", []):
                a = an[path]
                f = enclosing(a["funcs"], line)
                if f is None or not fn_returns_bool(a["texts"], a["lines"], f):
                    continue
                k2 = f"{f['name'].split('::')[-1]}@{path}"
                if k2 in gates:
                    gates[k2]["names"] |= gates[key]["names"]
                    continue
                gates[k2] = {"kind": "fn", "name": f["name"].split("::")[-1], "names": set(gates[key]["names"]),
                             "file": path, "via": key}
                added = True
        if not added:
            break
        uses = find_use_branches(an, gates, an.defs)
    hatches: dict[str, dict] = {}
    for s in sites:
        src_file = an[s["file"]]["src_file"]
        h = hatches.setdefault(s["name"], {"name": s["name"], "files": set(), "reads": 0, "sets": 0, "defs": 0,
                                           "direct_branches": 0, "gates": set(), "sites": []})
        h["files"].add(src_file)
        if s["kind"] in ("read", "compile"):
            h["reads"] += 1
            if s.get("direct_branch"):
                h["direct_branches"] += 1
            if s.get("gate"):
                h["gates"].add(s["gate"])
        elif s["kind"] == "set":
            h["sets"] += 1
        elif s["kind"] == "def":
            h["defs"] += 1
        line = "?" if s["src_line"] is None else f"{'~' if s['approx'] else ''}{s['src_line']}"
        h["sites"].append(f"{src_file}:{line}:{s['kind']}" + (f" ({s['fn']})" if s.get("fn") else ""))
    for key, g in gates.items():
        for n in g["names"]:
            if n in hatches:
                hatches[n]["gates"].add(key)
    for u in uses.values():
        u.pop("other_at", None)
    for h in hatches.values():
        h["gate_branch_uses"] = sum(uses.get(g, {}).get("branch", 0) for g in h["gates"])
        h["gate_uses"] = sum(uses.get(g, {}).get("branch", 0) + uses.get(g, {}).get("other", 0) for g in h["gates"])
    gate_list = {g: {"kind": v["kind"], "name": v["name"], "file": an[v["file"]]["src_file"], "env": sorted(v["names"]),
                     "via": v.get("via"), **uses.get(g, {"branch": 0, "other": 0, "sites": []})}
                 for g, v in gates.items()}
    return hatches, gate_list


def hatch_inventory(sha: str, src_an: dict) -> dict:
    """The escape-hatch inventory of `sha`: shipped reads from the expanded default build, feature-only
    reads from the expanded features build (qexpand.py)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import qexpand

    default = qexpand.expand(sha, "default")
    feats = qexpand.expand(sha, "features")
    hd, gd = inventory_of(default, src_an)
    hf, gf = inventory_of(feats, src_an)
    out = []
    for name in sorted(set(hd) | set(hf)):
        shipped = name in hd and hd[name]["reads"] > 0
        h = hd[name] if shipped or name not in hf or hf[name]["reads"] == 0 else hf[name]
        gates = gd if h is hd.get(name) else gf
        feat = [] if shipped or h is hd.get(name) else feats["features"]
        e = {**h, "files": sorted(h["files"]), "gates": sorted(h["gates"]), "features": feat,
             "shipped_reads": h["reads"] if shipped else 0,
             # a switch: read into a bool gate (fn or static) or branched on where it is read
             "fallback": shipped and (h["direct_branches"] > 0 or bool(h["gates"])),
             # read in the default build (not only in the diagnostics/test-hooks build)
             "read_in_prod": shipped,
             "gate_names": {g: gates[g]["name"] for g in h["gates"]}}
        e["class"] = hatch_class(e)
        e["class_by_name"] = bool(TESTHOOK_RE.search(name) or DIAG_RE.search(name) or VERIFY_RE.search(name))
        out.append(e)
    gate_list = dict(gd)
    for k, v in gf.items():
        if k not in gate_list:
            gate_list[k] = {**v, "feature_only": True}
    return {"hatches": out, "gates": gate_list,
            "expansion": {v["variant"]: {"toolchain": v["toolchain"], "features": v["features"], "seconds": v["seconds"],
                                         "crates": [{k: c[k] for k in ("crate", "kind", "root", "env_deps", "unclaimed")}
                                                    | {"files": len(c["files"])} for c in v["crates"]]}
                          for v in (default, feats)}}


def build_snapshot(sha: str, with_clippy: bool) -> dict:
    tree = crates_tree(sha)
    cache = CACHE / "snap" / f"{tree}-v{VERSION}.json"
    snap = None
    if cache.exists():
        snap = json.loads(cache.read_text())
    else:
        snap = measure_tree(sha, tree)
        cache.parent.mkdir(parents=True, exist_ok=True)
        tmp = cache.with_suffix(".tmp")
        tmp.write_text(json.dumps(snap))
        tmp.replace(cache)
    snap["sha"] = sha
    if with_clippy:
        snap["clippy"] = clippy_counts(sha)
    return snap


def measure_tree(sha: str, tree: str) -> dict:
    t0 = time.time()
    (CACHE / "tmp").mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="q-", dir=CACHE / "tmp"))
    try:
        src_root = work / "src"
        src_root.mkdir()
        arch = subprocess.run(["git", "archive", "--format=tar", sha, "crates"], cwd=REPO, check=True, capture_output=True).stdout
        subprocess.run(["tar", "-x", "-C", str(src_root)], input=arch, check=True)
        files = sorted(str(p.relative_to(src_root)) for p in (src_root / "crates").rglob("*.rs"))
        fileset = set(files)
        rca_out = work / "rca"
        rca_out.mkdir()
        if not RCA.exists():
            sys.exit(f"rust-code-analysis-cli not found at {RCA}; run `quality.sh install`")
        subprocess.run([str(RCA), "-m", "-p", "crates", "-I", "*.rs", "-O", "json", "-j", str(min(16, os.cpu_count() or 4)),
                        "-o", str(rca_out)], cwd=src_root, check=True, capture_output=True)
        an: dict[str, dict] = {}
        for path in files:
            src = (src_root / path).read_text(errors="replace")
            head = "\n".join(src.split("\n", 15)[:15])
            if is_generated(path, head):
                fk = "generated"
            else:
                fk = classify_path(path) or "prod"
            a = analyze_file(path, src, "test" if fk == "test" else "prod")
            a["fkind"] = fk
            an[path] = a
        # `#[cfg(test)] mod x;` files are test files
        changed = True
        while changed:
            changed = False
            for path, a in list(an.items()):
                for name, pattr in a["mods"]:
                    for c in resolve_mod(path, name, pattr, fileset):
                        if an[c]["fkind"] == "prod":
                            src = (src_root / c).read_text(errors="replace")
                            b = analyze_file(c, src, "test")
                            b["fkind"] = "test"
                            an[c] = b
                            changed = True
                        # its child module dir is test too
                        sub = c[:-3] + "/" if not c.endswith("/mod.rs") else c[: -len("mod.rs")]
                        for other in files:
                            if other.startswith(sub) and an[other]["fkind"] == "prod":
                                src = (src_root / other).read_text(errors="replace")
                                b = analyze_file(other, src, "test")
                                b["fkind"] = "test"
                                an[other] = b
                                changed = True
        for path, a in an.items():
            a["funcs"] = rca_functions(rca_out, src_root, path)

        inv = hatch_inventory(sha, an)
        snap = summarize(sha, tree, an, inv)
        snap["measure_seconds"] = round(time.time() - t0, 1)
        return snap
    finally:
        shutil.rmtree(work, ignore_errors=True)


def summarize(sha: str, tree: str, an: dict, inv: dict) -> dict:
    files_out = {}
    totals = Counter()
    areas: dict[str, Counter] = defaultdict(Counter)
    hyg_total = {"prod": Counter(), "test": Counter()}
    hyg_files: dict[str, dict] = {}
    allow_total = {"prod": Counter(), "test": Counter()}
    funcs_out = []
    for path, a in an.items():
        fk = a["fkind"]
        files_out[path] = {"kind": fk, "spans": a["spans"]}
        if fk == "generated":
            totals["files_generated"] += 1
            totals["lines_generated"] += a["nlines"]
            continue
        totals["files_" + fk] += 1
        totals["code_prod"] += a["code_prod"]
        totals["code_test"] += a["code_test"]
        ar = area_of(path)
        areas[ar]["code_prod"] += a["code_prod"]
        areas[ar]["code_test"] += a["code_test"]
        for s in ("prod", "test"):
            hyg_total[s].update(a["hyg"][s])
            allow_total[s].update(a["allow_lints"][s])
        if a["hyg"]["prod"]:
            hyg_files[path] = dict(a["hyg"]["prod"])
            for k2, v in a["hyg"]["prod"].items():
                areas[ar]["hyg_" + k2] += v
        for f in a["funcs"]:
            test = fk == "test" or in_spans(a["spans"], f["start"])
            funcs_out.append({"file": path, **f, "test": test})
            if not test:
                areas[ar]["fn_prod"] += 1
                if f["cog"] > COG_THRESHOLDS[0]:
                    areas[ar]["fn_cog_gt25"] += 1

    # function name disambiguation (same file+name)
    seen = Counter()
    for f in funcs_out:
        key = f"{f['file']}::{f['name']}"
        seen[key] += 1
        f["key"] = key if seen[key] == 1 else f"{key}#{seen[key]}"

    prod_fns = [f for f in funcs_out if not f["test"]]
    test_fns = [f for f in funcs_out if f["test"]]

    def dist(fns):
        cog = [f["cog"] for f in fns]
        cyc = [f["cyc"] for f in fns]
        return {
            "count": len(fns),
            "cog": {"p50": pctl(cog, 50), "p90": pctl(cog, 90), "p99": pctl(cog, 99), "max": max(cog, default=0),
                    "sum": sum(cog), **{f"gt{t}": sum(1 for c in cog if c > t) for t in COG_THRESHOLDS}},
            "cyc": {"p50": pctl(cyc, 50), "p90": pctl(cyc, 90), "p99": pctl(cyc, 99), "max": max(cyc, default=0),
                    **{f"gt{t}": sum(1 for c in cyc if c > t) for t in CYC_THRESHOLDS}},
        }

    features = Counter()
    feature_sites = defaultdict(list)
    for path, a in an.items():
        if a["fkind"] == "prod":
            for ft in a["features"]:
                features[ft["feature"]] += 1
                if len(feature_sites[ft["feature"]]) < 8:
                    feature_sites[ft["feature"]].append(f"{path}:{ft['line']}")

    # duplication
    intern: dict[str, int] = {}
    dfiles = []
    texts_ref = []
    tfiles = []
    for path in sorted(an):
        a = an[path]
        if a["fkind"] == "generated":
            continue
        ids = array("i")
        lns = []
        tex = []
        for t, ln in zip(a["texts"], a["lines"]):
            test = a["fkind"] == "test" or in_spans(a["spans"], ln)
            if test:
                continue
            ids.append(intern.setdefault(t, len(intern)))
            lns.append(ln)
            tex.append(t)
        if len(ids):
            dfiles.append((path, ids, lns))
            texts_ref.append(tex)
    blocks, dup_lines = find_clones(dfiles, DUP_MIN_TOKENS, DUP_MIN_LINES, lambda fi, a0, a1: texts_ref[fi][a0:a1])
    prod_code_lines = 0
    dup_code = 0
    dup_by_file = {}
    for (path, ids, lns) in dfiles:
        ls = set(lns)
        prod_code_lines += len(ls)
        d = len(ls & dup_lines.get(path, set()))
        dup_code += d
        if d:
            dup_by_file[path] = d
    for p, c in dup_by_file.items():
        areas[area_of(p)]["dup_lines"] += c

    # drop heavy fields
    return {
        "version": VERSION, "tree": tree, "sha": sha,
        "totals": dict(totals),
        "areas": {k: dict(v) for k, v in sorted(areas.items())},
        "functions": {"prod": dist(prod_fns), "test": dist(test_fns)},
        "funcs": [{k: f[k] for k in ("key", "file", "name", "start", "end", "cyc", "cog", "sloc", "test")} for f in funcs_out if not f["test"]],
        "hygiene": {s: dict(hyg_total[s]) for s in hyg_total},
        "hygiene_files": hyg_files,
        "allow_lints": {s: dict(allow_total[s].most_common()) for s in allow_total},
        "hatches": inv["hatches"],
        "gates": inv["gates"],
        "expansion": inv["expansion"],
        "features": {k: {"count": v, "sites": feature_sites[k]} for k, v in sorted(features.items())},
        "dup": {"min_tokens": DUP_MIN_TOKENS, "min_lines": DUP_MIN_LINES, "prod_code_lines": prod_code_lines,
                "dup_lines": dup_code, "pct": round(100 * dup_code / max(1, prod_code_lines), 2),
                "blocks": sorted(blocks, key=lambda b: -b["tokens"]), "by_file": dup_by_file},
        "files": files_out,
    }


