def first_parent_merges(base: str, branch: str) -> list[tuple[str, str]]:
    out = git("log", "--first-parent", "--reverse", "--format=%H %P%x00%s", f"{base}..{branch}")
    res = []
    for ln in out.splitlines():
        head, subj = ln.split("\x00", 1)
        parts = head.split()
        if len(parts) > 2:
            res.append((parts[0], subj))
    return res


def cmd_history(args) -> None:
    t0 = time.time()
    base_sha = rev_sha(args.base)
    branch_sha = rev_sha(args.branch)
    points = [(base_sha, args.base)] + [(s, subj) for s, subj in first_parent_merges(base_sha, branch_sha)]
    if points[-1][0] != branch_sha:
        points.append((branch_sha, f"{args.branch} head"))
    snaps = []
    for sha, label in points:
        snaps.append((sha, label, build_snapshot(sha, False)))
    rows = []
    md = [f"## Quality history {args.base}..{args.branch} (first-parent merges; each delta against the previous point)", ""]
    md.append("| point | prod net | prod +/− | test +/− | files | env read (switches) | behavior switches | new env names | gate br. | fn cog>25 | >50 | cog max | dup % | unwrap | expect | allow | TODO+ |")
    md.append("|---|---:|---:|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    deltas = []
    s0 = snaps[0][2]
    h0 = s0["hygiene"]["prod"]
    md.append(f"| {args.base} {snaps[0][0][:9]} | | | | | {sum(1 for h in s0['hatches'] if h['read_in_prod'])} ({sum(1 for h in s0['hatches'] if h['fallback'])}) | "
              f"{sum(1 for h in s0['hatches'] if h['class'] == 'behavior')} | | "
              f"{sum(g['branch'] for g in s0['gates'].values() if not g.get('feature_only'))} | {s0['functions']['prod']['cog']['gt25']} | {s0['functions']['prod']['cog']['gt50']} | "
              f"{s0['functions']['prod']['cog']['max']} | {s0['dup']['pct']} | {h0.get('unwrap', 0)} | {h0.get('expect', 0)} | {h0.get('allow_attr', 0)} | "
              f"{sum(h0.get(k, 0) for k in ('TODO', 'FIXME', 'HACK', 'XXX'))} |")
    for (pa, la, a), (pb, lb, b) in zip(snaps, snaps[1:]):
        d = delta(a, b)
        d["label"] = lb
        deltas.append(d)
        c = d["churn"]
        hb = b["hygiene"]["prod"]
        ha = a["hygiene"]["prod"]

        def dd(k):
            return f"{hb.get(k, 0)} ({sgn(hb.get(k, 0) - ha.get(k, 0))})"

        tb = sum(hb.get(k, 0) for k in ("TODO", "FIXME", "HACK", "XXX"))
        ta = sum(ha.get(k, 0) for k in ("TODO", "FIXME", "HACK", "XXX"))
        fb, fa = b["functions"]["prod"]["cog"], a["functions"]["prod"]["cog"]
        m = re.match(r"Merge branch '[^']*' into (\S+)", lb)
        lbl = (m.group(1).split("/")[-1] if m else lb.removeprefix("Merge ").split(":")[0])[:40]
        md.append(f"| {lbl} {pb[:9]} | {sgn(c['prod_net'])} | +{c['prod_add']}/−{c['prod_del']} | +{c['test_add']}/−{c['test_del']} | {c['files_touched']} | "
                  f"{d['hatch_counts']['rev']} ({d['hatch_counts']['fallback_rev']}) | {d['hatch_classes']['behavior'][1]} ({sgn(d['hatch_classes']['behavior'][1] - d['hatch_classes']['behavior'][0])}) | "
                  f"{', '.join(h['name'].removeprefix('GOPORT_') + ' (' + h['class'][:4] + ')' for h in d['hatches_new']) or '-'} | "
                  f"{d['gates_branch']['rev']} ({sgn(d['gates_branch']['rev'] - d['gates_branch']['base'])}) | "
                  f"{fb['gt25']} ({sgn(fb['gt25'] - fa['gt25'])}) | {fb['gt50']} ({sgn(fb['gt50'] - fa['gt50'])}) | {fb['max']} | "
                  f"{b['dup']['pct']} ({sgn(round(b['dup']['pct'] - a['dup']['pct'], 2))}) | {dd('unwrap')} | {dd('expect')} | {dd('allow_attr')} | {tb} ({sgn(tb - ta)}) |")
    md.append("")
    for d in deltas:
        if d["churn"]["files_touched"] or d["hatches_new"] or d["hatches_changed"]:
            md += md_delta(d, f"— {d['label']}")
    secs = round(time.time() - t0, 1)
    md.append(f"_quality.sh history: {len(points)} points, {secs} s_")
    outdir = Path(args.out) if args.out else CACHE / "reports" / f"history-{branch_sha[:9]}"
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "history.json").write_text(json.dumps({"points": [(s, l) for s, l, _ in snaps], "deltas": deltas, "seconds": secs}, indent=1))
    text = "\n".join(md)
    (outdir / "history.md").write_text(text + "\n")
    print(text)
    print(f"\n_JSON: {outdir / 'history.json'}_")


