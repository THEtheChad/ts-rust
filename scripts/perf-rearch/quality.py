def clippy_counts(sha: str) -> dict:
    """Two clippy passes: the repo's config (its crate roots allow clippy::all and
    clippy::pedantic, so this is near zero) and `--force-warn clippy::all`, which
    overrides those allows and is the useful count."""
    key = git("rev-parse", f"{sha}^{{tree}}").strip()
    cache = CACHE / "clippy" / f"{key}-v3.json"
    if cache.exists():
        return json.loads(cache.read_text())
    # one clippy worktree for all callers: hold its lock for the checkout and both passes
    import fcntl
    (CACHE / "clippy").mkdir(parents=True, exist_ok=True)
    with open(CACHE / "clippy" / "worktree.lock", "w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        if cache.exists():
            return json.loads(cache.read_text())
        return clippy_locked(sha, key, cache)


def clippy_locked(sha: str, key: str, cache: Path) -> dict:
    wt = CACHE / "clippy-wt"
    if not (wt / ".git").exists():
        subprocess.run(["git", "worktree", "add", "--detach", str(wt), sha], cwd=REPO, check=True, capture_output=True)
    else:
        subprocess.run(["git", "checkout", "--detach", "--force", sha], cwd=wt, check=True, capture_output=True)
    res = {"note": "cargo clippy --workspace (lib+bins, no tests), deduped by primary span, crates/ only; "
                   "'config' = the repo's lint config, 'forced' = -- --force-warn clippy::all"}
    ok = True
    for name, extra in (("config", []), ("forced", ["--", "--force-warn", "clippy::all"])):
        r = clippy_pass(wt, key, name, extra)
        res[name] = r
        ok = ok and r["ok"]
    if ok:
        cache.write_text(json.dumps(res))
    return res


def clippy_pass(wt: Path, key: str, name: str, extra: list[str]) -> dict:
    t0 = time.time()
    log = CACHE / "clippy" / f"{key}-{name}.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env.pop("CARGO_TARGET_DIR", None)
    with open(log, "w") as lf:
        p = subprocess.run(["scripts/run-cargo-capped.sh", "clippy", "--workspace", "--message-format=json", *extra],
                           cwd=wt, stdout=subprocess.PIPE, stderr=lf, text=True, env=env)
    seen = set()
    by_lint = Counter()
    by_area = Counter()
    by_file = Counter()
    for line in p.stdout.splitlines():
        try:
            m = json.loads(line)
        except ValueError:
            continue
        if m.get("reason") != "compiler-message":
            continue
        msg = m["message"]
        if msg.get("level") not in ("warning", "error") or not msg.get("code"):
            continue
        spans = [sp for sp in msg.get("spans", []) if sp.get("is_primary")]
        if not spans:
            continue
        sp = spans[0]
        fn = os.path.normpath(sp["file_name"])  # parts/ crates name src files through ../../src
        if not fn.startswith("crates/"):
            continue
        k = (msg["code"]["code"], fn, sp["line_start"], sp["column_start"])
        if k in seen:
            continue
        seen.add(k)
        by_lint[msg["code"]["code"]] += 1
        by_area[area_of(fn)] += 1
        by_file[fn] += 1
    return {"ok": p.returncode == 0, "rc": p.returncode, "seconds": round(time.time() - t0, 1),
            "total": sum(by_lint.values()), "clippy_total": sum(v for k, v in by_lint.items() if k.startswith("clippy::")),
            "by_lint": dict(by_lint.most_common()), "by_area": dict(by_area.most_common()),
            "by_file": dict(by_file.most_common(30))}


