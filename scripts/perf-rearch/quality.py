# churn

HUNK_RE = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


def churn(base: dict, rev: dict) -> dict:
    out = git("diff", "-U0", "--no-color", "-M", base["sha"], rev["sha"], "--", "crates")
    c = Counter()
    files = {"prod": set(), "test": set(), "generated": set(), "other": set()}
    per_file = Counter()
    old = new = None

    def kind_of(snap, path, line):
        if path is None or not path.endswith(".rs"):
            return "other"
        f = snap["files"].get(path)
        if f is None:
            return "other"
        if f["kind"] in ("generated", "test"):
            return f["kind"]
        return "test" if in_spans(f["spans"], line) else "prod"

    for ln in out.splitlines():
        if ln.startswith("diff --git"):
            old = new = None
        elif ln.startswith("--- "):
            old = None if ln[4:] == "/dev/null" else ln[6:]
        elif ln.startswith("+++ "):
            new = None if ln[4:] == "/dev/null" else ln[6:]
        elif ln.startswith("Binary files"):
            files["other"].add(ln)
        elif ln.startswith("@@"):
            m = HUNK_RE.match(ln)
            a, b, cc, d = int(m[1]), int(m[2] or 1), int(m[3]), int(m[4] or 1)
            for x in range(a, a + b):
                k = kind_of(base, old, x)
                c[k + "_del"] += 1
                files[k].add(old)
                if k == "prod":
                    per_file[old] -= 1
            for x in range(cc, cc + d):
                k = kind_of(rev, new, x)
                c[k + "_add"] += 1
                files[k].add(new)
                if k == "prod":
                    per_file[new] += 1
    touched = set().union(*files.values())
    return {
        **{k: c.get(k, 0) for k in ("prod_add", "prod_del", "test_add", "test_del", "generated_add", "generated_del", "other_add", "other_del")},
        "prod_net": c.get("prod_add", 0) - c.get("prod_del", 0),
        "test_net": c.get("test_add", 0) - c.get("test_del", 0),
        "files_touched": len(touched), "files_prod": len(files["prod"]), "files_test": len(files["test"]),
        "test_to_prod_add": round(c.get("test_add", 0) / max(1, c.get("prod_add", 0)), 2),
        "prod_net_by_file": dict(sorted(per_file.items(), key=lambda kv: -abs(kv[1]))[:15]),
    }


