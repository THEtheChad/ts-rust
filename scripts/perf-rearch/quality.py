def pctl(vals: list[int], p: float) -> float:
    if not vals:
        return 0
    s = sorted(vals)
    idx = min(len(s) - 1, max(0, int(round(p / 100 * (len(s) - 1)))))
    return s[idx]


DIAG_RE = re.compile(r"(STATS|_LOG|DUMP|TIMES|TRACE|DEBUG)$|_LOG_|CALL_LOG")
VERIFY_RE = re.compile(r"VERIFY|_CHECK$|_CHECK_|CHECK_VERSION")
TESTHOOK_RE = re.compile(r"_TEST_|_CHILD($|_)")


def hatch_class(h: dict) -> str:
    """By name and use (heuristic): test-hook, diagnostic, verification, tuning or behavior. A name
    read only in the diagnostics/test-hooks build that no name rule places is a test-hook."""
    n = h["name"]
    if TESTHOOK_RE.search(n):
        return "test-hook"
    if DIAG_RE.search(n):
        return "diagnostic"
    if VERIFY_RE.search(n):
        return "verification"
    if not h["read_in_prod"] and h["features"]:
        return "test-hook"
    if not h["fallback"]:
        return "tuning"
    return "behavior"


def find_use_branches(an, gates: dict, defs: Counter):
    """For each gate (bool fn/static): (branch uses, other uses) in the shipped code (`an`: the
    pieces of one expanded build, analyzed on access; `defs`: fn definitions per name).

    A name defined once among fns counts everywhere (not as a method: `.name(`); a common name
    (`enabled`) only in its own file or as `<module>::name`."""
    by_name: dict[str, list[str]] = defaultdict(list)
    for key, g in gates.items():
        by_name[g["name"]].append(key)
    # the pieces that can hold a counted use: any piece for a unique name, else the gate's own
    # piece and pieces naming `<stem>::name`
    unique = {n for n, ks in by_name.items() if defs[n] == 1 and len(ks) == 1}
    keys = set(an.keys_with(unique))
    qualified = set()
    for n, ks in by_name.items():
        if n in unique:
            continue
        for k in ks:
            keys.add(gates[k]["file"])
            stem = os.path.basename(an.src.get(gates[k]["file"], gates[k]["file"]))[:-3]
            if stem == "mod":
                stem = os.path.basename(os.path.dirname(gates[k]["file"]))
            qualified.add(rf"\b{re.escape(stem)}\s*::\s*{re.escape(n)}\b")
    if qualified:
        rx = re.compile("|".join(sorted(qualified)))
        names = tuple(n for n in by_name if n not in unique)
        keys |= {k for k, t in an.text.items() if any(n in t for n in names) and rx.search(t)}
    res = {}
    for path in sorted(keys):
        a = an[path]
        texts, kinds, lines = a["texts"], a["kinds"], a["lines"]
        for i, t in enumerate(texts):
            if kinds[i] != K_ID or t not in by_name:
                continue
            nxt = texts[i + 1] if i + 1 < len(texts) else ""
            prv = texts[i - 1] if i else ""
            if prv == "fn" or prv in ("static", "const"):
                continue  # definition
            if prv == ".":
                continue  # a method of the same name
            key = None
            for k in by_name[t]:
                g = gates[k]
                if path == g["file"]:
                    key = k
                    break
                stem = os.path.basename(an.src.get(g["file"], g["file"]))[:-3]
                if stem == "mod":
                    stem = os.path.basename(os.path.dirname(g["file"]))
                if prv == "::" and i >= 2 and texts[i - 2] == stem:
                    key = k
                    break
                if defs[t] == 1 and len(by_name[t]) == 1:
                    key = k
            if key is None:
                continue
            if gates[key]["kind"] == "fn" and nxt != "(":
                continue  # a variable or field of the same name
            if gates[key]["kind"] == "static" and nxt == "(":
                continue
            pre = statement_prefix(texts, i)
            br = any(w in BRANCH_WORDS for w in pre) or prv in ("!",) and "if" in pre
            r = res.setdefault(key, {"branch": 0, "other": 0, "sites": [], "other_at": []})
            r["branch" if br else "other"] += 1
            if not br:
                r["other_at"].append((path, i, lines[i]))
            if len(r["sites"]) < 12:
                r["sites"].append(f"{path}:{lines[i]}")
    return res


def enclosing(funcs: list[dict], line: int):
    best = None
    for f in funcs:
        if f["start"] <= line <= f["end"] and (best is None or f["end"] - f["start"] < best["end"] - best["start"]):
            best = f
    return best


def fn_returns_bool(texts: list[str], lines: list[int], f: dict) -> bool:
    # find `fn name` at the function's start line and read the signature up to '{'
    short = f["name"].split("::")[-1]
    for i, ln in enumerate(lines):
        if ln < f["start"]:
            continue
        if ln > f["start"] + 3:
            break
        if texts[i] == "fn" and i + 1 < len(texts) and texts[i + 1] == short:
            j = i + 2
            while j < len(texts) and texts[j] not in ("{", ";"):
                j += 1
            sig = texts[i:j]
            if "->" in sig:
                ret = sig[sig.index("->") + 1 :]
                return ret[-1:] == ["bool"] or ret[:1] == ["bool"]
            return False
    return False


def static_holder(texts: list[str], tok: int):
    """Name of a `static`/`const` item whose initializer holds token tok (top-level LazyLock etc.)."""
    depth = 0
    j = tok
    while j >= 0:
        t = texts[j]
        if t in ("}", ")", "]"):
            depth += 1
        elif t in ("{", "(", "["):
            depth -= 1
        elif t == ";" and depth <= 0:
            return None
        if t in ("static", "const") and depth <= 0 and j + 1 < len(texts):
            k = j + 1
            if texts[k] == "mut":
                k += 1
            nm = texts[k]
            # the item's type, up to `=`: a switch only when it holds a bool
            ty = []
            m = k + 2
            while m < len(texts) and texts[m] != "=":
                ty.append(texts[m])
                m += 1
            return nm if "bool" in ty else None
        if t == "fn" and depth < 0:
            return None
        j -= 1
    return None


