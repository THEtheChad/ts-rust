# Rust lexer (regex; good enough for counting: nested block comments are
# treated as flat, which only matters for comment text)

TOKEN_RE = re.compile(
    r"""
    (?P<ws>\s+)
  | (?P<lc>//[^\n]*)
  | (?P<bc>/\*[\s\S]*?\*/)
  | (?P<raw>[bc]?r(?P<h>\#*)"[\s\S]*?"(?P=h))
  | (?P<str>[bc]?"(?:\\[\s\S]|[^"\\])*")
  | (?P<chr>b?'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F_]+\}|[^\n])|[^'\\\n])')
  | (?P<life>'[A-Za-z_][A-Za-z0-9_]*)
  | (?P<id>(?:r\#)?[A-Za-z_][A-Za-z0-9_]*)
  | (?P<num>[0-9][0-9A-Za-z_]*(?:\.(?![.A-Za-z_])[0-9A-Za-z_]*)?(?:[eE][+-][0-9_]+)?)
  | (?P<p>::|->|=>|==|!=|<=|>=|&&|\|\||\.\.=|\.\.\.|\.\.|<<=|>>=|\+=|-=|\*=|/=|%=|\^=|&=|\|=|[^\s])
    """,
    re.X,
)

# token kinds
K_ID, K_P, K_STR, K_NUM, K_CHR, K_LIFE, K_COMMENT = range(7)
_KIND = {"lc": K_COMMENT, "bc": K_COMMENT, "raw": K_STR, "str": K_STR, "chr": K_CHR, "life": K_LIFE,
         "id": K_ID, "num": K_NUM, "p": K_P}


def lex(src: str):
    """Returns (kinds, texts, lines, comments) with comments split out as (line, text)."""
    kinds: list[int] = []
    texts: list[str] = []
    lines: list[int] = []
    comments: list[tuple[int, str]] = []
    line = 1
    last = 0
    for m in TOKEN_RE.finditer(src):
        g = m.lastgroup
        if g == "h":  # raw string group name resolution
            g = "raw"
        if g == "ws":
            continue
        start = m.start()
        line += src.count("\n", last, start)
        last = start
        text = m.group()
        k = _KIND[g]
        if k == K_COMMENT:
            comments.append((line, text))
            continue
        kinds.append(k)
        texts.append(text)
        lines.append(line)
    return kinds, texts, lines, comments


