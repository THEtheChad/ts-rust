# duplication (token-window hashing over production code)

MOD = (1 << 61) - 1
BASE = 1_000_003


def find_clones(files: list[tuple[str, array, list[int]]], min_tokens: int, min_lines: int, texts_of):
    """files: (path, token ids, token lines). Returns (blocks, dup line sets per file)."""
    W = min_tokens
    pw = pow(BASE, W - 1, MOD)
    first: dict[int, tuple[int, int]] = {}
    hashes: list[list[int]] = []
    blocks = []
    dup_lines: dict[str, set[int]] = defaultdict(set)
    for fi, (path, ids, lns) in enumerate(files):
        n = len(ids)
        hs: list[int] = []
        if n >= W:
            h = 0
            for x in ids[:W]:
                h = (h * BASE + x + 1) % MOD
            hs.append(h)
            for i in range(W, n):
                h = ((h - (ids[i - W] + 1) * pw) * BASE + ids[i] + 1) % MOD
                hs.append(h)
        hashes.append(hs)
        i = 0
        m = len(hs)
        while i < m:
            h = hs[i]
            prev = first.get(h)
            if prev is None:
                first[h] = (fi, i)
                i += 1
                continue
            f0, i0 = prev
            if f0 == fi and i0 + W > i:
                i += 1
                continue
            hs0 = hashes[f0]
            ids0 = files[f0][1]
            if ids0[i0 : i0 + W] != ids[i : i + W]:
                i += 1
                continue
            k = 0
            while i + k + 1 < m and i0 + k + 1 < len(hs0) and hs0[i0 + k + 1] == hs[i + k + 1] \
                    and not (f0 == fi and i0 + k + 1 >= i):
                k += 1
            L = W + k
            if ids0[i0 : i0 + L] != ids[i : i + L]:
                L = W
                k = 0
            a0, a1 = files[f0][2][i0], files[f0][2][i0 + L - 1]
            b0, b1 = lns[i], lns[i + L - 1]
            if b1 - b0 + 1 >= min_lines:
                frag = " ".join(texts_of(fi, i, i + L))
                bid = hashlib.sha1(frag.encode()).hexdigest()[:12]
                blocks.append({"id": bid, "tokens": L, "lines": b1 - b0 + 1,
                               "a": f"{files[f0][0]}:{a0}-{a1}", "b": f"{path}:{b0}-{b1}"})
                dup_lines[files[f0][0]].update(range(a0, a1 + 1))
                dup_lines[path].update(range(b0, b1 + 1))
            for j in range(i, i + k + 1):
                first.setdefault(hs[j], (fi, j))
            i += k + 1
    return blocks, dup_lines


